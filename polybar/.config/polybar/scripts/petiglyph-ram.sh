#!/usr/bin/env bash
BU_HEX=(
1001AB 1001AC 1001AD 1001AE 1001AF 1001B0 1001B1 1001B2
1001B3 1001B4 1001B5 1001B6 1001B7 1001B8 1001B9 1001BA
1001BB 1001BC 1001BD 1001BE 1001BF 1001C0 1001C1 1001C2
1001C3 1001C4 1001C5 1001C6 1001C7 1001C8 1001C9 1001CA
1001CB 1001CC 1001CD 1001CE 1001CF 1001D0 1001D1 1001D2
1001D3 1001D4 1001D5 1001D6 1001D7 1001D8 1001D9 1001DA
1001DB 1001DC 1001DD 1001DE 1001DF 1001E0 1001E1 1001E2
1001E3 1001E4 1001E5 1001E6 1001E7 1001E8 1001E9 1001EA
)
I=0
RAM="?"
S=0

while true; do
  NOW=$(date +%s)
  if (( NOW != S )); then
    RAM=$(free -m | awk '/^Mem:/ {print $3}')
    RAM=${RAM:-?}
    S=$NOW
  fi
  printf "\U${BU_HEX[$I]} ${RAM}M\n"
  ((I = (I + 1) % ${#BU_HEX[@]}))
  sleep 0.033
done
