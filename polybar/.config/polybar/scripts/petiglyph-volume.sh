I=0

while true; do
  MIX=$(amixer get Master 2>/dev/null)
  VOL=$(echo "$MIX" | grep -oP '\d+%' | head -1 | tr -d '%')
  MUTED=$(echo "$MIX" | grep -oP '\[off\]')
  if [[ -n "$MUTED" ]]; then
    printf "\U${VL_HEX[$I]} Muted\n"
  elif [[ -n "$VOL" ]]; then
    printf "\U${VL_HEX[$I]} ${VOL}%%\n"
  else
    printf "\U${VL_HEX[$I]} ?\n"
  fi
  ((I = (I + 1) % ${#VL_HEX[@]}))
  sleep 0.033
done
