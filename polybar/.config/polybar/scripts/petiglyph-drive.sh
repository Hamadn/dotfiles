I=0
FREE="?"
S=0

while true; do
  NOW=$(date +%s)
  if (( NOW > S )); then
    FREE=$(df -h / | awk 'NR==2 {print $4}')
    S=$((NOW + 30))
  fi
  printf "\U${CP_HEX[$I]} $FREE\n"
  ((I = (I + 1) % ${#CP_HEX[@]}))
  sleep 0.033
done
