#!/usr/bin/env bash
CP_HEX=(
100098 100099 10009A 10009B 10009C 10009D 10009E 10009F
1000A0 1000A1 1000A2 1000A3 1000A4 1000A5 1000A6 1000A7
1000A8 1000A9 1000AA 1000AB 1000AC 1000AD 1000AE 1000AF
1000B0 1000B1 1000B2 1000B3 1000B4 1000B5 1000B6 1000B7
1000B8 1000B9 1000BA 1000BB 1000BC 1000BD 1000BE 1000BF
1000C0 1000C1 1000C2 1000C3 1000C4 1000C5 1000C6 1000C7
1000C8 1000C9 1000CA 1000CB 1000CC 1000CD 1000CE 1000CF
1000D0 1000D1 1000D2 1000D3 1000D4 1000D5 1000D6 1000D7
1000D8 1000D9 1000DA 1000DB 1000DC 1000DD 1000DE 1000DF
1000E0 1000E1 1000E2 1000E3 1000E4 1000E5 1000E6 1000E7
1000E8 1000E9 1000EA 1000EB 1000EC
)
I=0
CPU="?"
S=0

while true; do
  NOW=$(date +%s)
  if (( NOW != S )); then
    CPU=$(top -bn1 2>/dev/null | grep "Cpu(s)" | awk '{print int($2)}')
    CPU=${CPU:-?}
    S=$NOW
  fi
  printf "\U${CP_HEX[$I]} $CPU%%\n"
  ((I = (I + 1) % ${#CP_HEX[@]}))
  sleep 0.033
done
