#!/usr/bin/env bash
BT_HEX=(
1002BF 1002C0 1002C1 1002C2 1002C3 1002C4 1002C5 1002C6
1002C7 1002C8 1002C9 1002CA 1002CB 1002CC 1002CD 1002CE
1002CF 1002D0 1002D1 1002D2 1002D3 1002D4 1002D5 1002D6
1002D7 1002D8 1002D9 1002DA 1002DB 1002DC 1002DD 1002DE
1002DF 1002E0 1002E1 1002E2 1002E3 1002E4 1002E5 1002E6
1002E7 1002E8 1002E9 1002EA 1002EB 1002EC 1002ED 1002EE
1002EF 1002F0 1002F1 1002F2 1002F3 1002F4 1002F5 1002F6
1002F7 1002F8 1002F9 1002FA 1002FB 1002FC 1002FD 1002FE
1002FF 100300 100301 100302 100303 100304 100305 100306
100307
)
I=0

while true; do
  STATUS=$(cat /sys/class/power_supply/BAT0/status 2>/dev/null)
  CAP=$(cat /sys/class/power_supply/BAT0/capacity 2>/dev/null)
  if [[ "$STATUS" == "Full" ]]; then
    printf "\U${BT_HEX[$I]} Full\n"
  elif [[ -n "$STATUS" && -n "$CAP" ]]; then
    printf "\U${BT_HEX[$I]} ${CAP}%%\n"
  else
    printf "\U${BT_HEX[$I]} ?\n"
  fi
  ((I = (I + 1) % ${#BT_HEX[@]}))
  sleep 0.033
done
