100057 100058 100059 10005A 10005B 10005C 10005D 10005E
10005F 100060 100061 100062 100063 100064 100065 100066
100067 100068 100069 10006A 10006B 10006C 10006D 10006E
10006F 100070 100071 100072 100073 100074 100075 100076
100077 100078 100079 10007A 10007B 10007C 10007D 10007E
10007F 100080 100081 100082 100083 100084 100085 100086
100087 100088 100089 10008A 10008B 10008C 10008D 10008E
10008F 100090 100091 100092 100093 100094 100095 100096
)
I=0
UPDATES="?"

REFRESH_INTERVAL=900
C=0

refresh_updates() {
  UPDATES=$(~/.config/polybar/forest/scripts/checkupdates 2>/dev/null | wc -l)
}

refresh_updates

while true; do
  printf "\U${CP_HEX[$I]} $UPDATES\n"
  ((I = (I + 1) % ${#CP_HEX[@]}))
  ((C++))
  if (( C >= REFRESH_INTERVAL )); then
    refresh_updates
    C=0
  fi
  sleep 0.033
done
