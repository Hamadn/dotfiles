#!/usr/bin/env bash
WF_HEX=(
100293 100294 100295 100296 100297 100298 100299 10029A
10029B 10029C 10029D 10029E 10029F 1002A0 1002A1 1002A2
1002A3 1002A4 1002A5 1002A6 1002A7 1002A8 1002A9 1002AA
1002AB 1002AC 1002AD 1002AE 1002AF 1002B0 1002B1 1002B2
1002B3 1002B4 1002B5 1002B6 1002B7 1002B8 1002B9 1002BA
1002BB 1002BC 1002BD 1002BE
)
I=0

while true; do
  ESSID=$(iwgetid -r 2>/dev/null)
  if [[ -n "$ESSID" ]]; then
    printf "\U${WF_HEX[$I]} $ESSID\n"
  else
    printf "\U${WF_HEX[$I]} Offline\n"
  fi
  ((I = (I + 1) % ${#WF_HEX[@]}))
  sleep 0.033
done
